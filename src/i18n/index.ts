const getBestDeviceLocale = () => {
  const locales = RNLocalize.getLocales();
  if (Array.isArray(locales) && locales.length > 0) {
    return resolveSupportedLocale(locales[0].languageTag);
  }

  const bestLanguage = RNLocalize.findBestLanguageTag(SUPPORTED_LOCALE_CODES);
  return resolveSupportedLocale(bestLanguage?.languageTag || 'en-US');
};

i18n.use(initReactI18next).init({
  resources: resourcesWithGlobalLocales,
  lng: getBestDeviceLocale(),
  fallbackLng: 'en',
  supportedLngs: ['en', 'pt', ...SUPPORTED_LOCALE_CODES],
  nonExplicitSupportedLngs: true,
  load: 'languageOnly',
  interpolation: { escapeValue: false },
  compatibilityJSON: 'v4',
});

export const LANGUAGE_STORAGE_KEY = '@Alert:Language';

export const getDeviceLanguage = () => {
  return getBestDeviceLocale();
};

export const loadStoredLanguage = async () => {
  try {
    const stored = await AsyncStorage.getItem(LANGUAGE_STORAGE_KEY);
    const target =
      stored === 'system' || !stored
        ? getDeviceLanguage()
        : resolveSupportedLocale(stored);
    if (i18n.language !== target) {
      await i18n.changeLanguage(target);
    }
    return stored ?? 'system';
  } catch {
    return 'system';
  }
};

export const setStoredLanguage = async (mode: 'system' | string) => {
  if (mode === 'system') {
    await AsyncStorage.removeItem(LANGUAGE_STORAGE_KEY);
  } else {
    const resolved = resolveSupportedLocale(mode);
    await AsyncStorage.setItem(LANGUAGE_STORAGE_KEY, resolved);
  }

  const target =
    mode === 'system' ? getDeviceLanguage() : resolveSupportedLocale(mode);
  await i18n.changeLanguage(target);
};

